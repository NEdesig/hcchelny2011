const express=require('express'),multer=require('multer'),fs=require('fs'),path=require('path'),crypto=require('crypto');
const PASS=process.env.ADMIN_PASSWORD||'change-me',ADMIN=process.env.ADMIN_PATH||'/panel-x7k2',PORT=process.env.PORT||3000;
const DB=path.join(__dirname,'data/db.json'),UP=path.join(__dirname,'uploads');
fs.mkdirSync(UP,{recursive:true});fs.mkdirSync(path.dirname(DB),{recursive:true});
const COLS=['clubs','news','stories','matches','leaders','albums','settings','standings','tops'];
let db=fs.existsSync(DB)?JSON.parse(fs.readFileSync(DB)):{};
COLS.forEach(c=>db[c]=db[c]||[]);
const save=()=>fs.writeFileSync(DB,JSON.stringify(db));
const app=express(),tokens=new Set();
const up=multer({storage:multer.diskStorage({destination:UP,filename:(q,f,cb)=>cb(null,Date.now()+'-'+Math.random().toString(36).slice(2,7)+path.extname(f.originalname))})});
app.use(express.json({limit:'5mb'}));
app.use('/uploads',express.static(UP));
app.use(express.static(path.join(__dirname,'public')));
app.get(ADMIN,(q,s)=>s.sendFile(path.join(__dirname,'admin/index.html')));
app.get('/api/all',(q,s)=>{const n=Date.now(),l=db.stories.length;
  db.stories=db.stories.filter(x=>!x.expires||new Date(x.expires)>n);if(l!=db.stories.length)save();s.json(db)});
app.post('/api/a/login',(q,s)=>{if(q.body.password!==PASS)return s.status(401).end();
  const t=crypto.randomUUID();tokens.add(t);s.json({token:t})});
app.use('/api/a',(q,s,n)=>tokens.has(q.get('x-token'))?n():s.status(401).end());
app.post('/api/a/upload',up.array('f'),(q,s)=>s.json(q.files.map(f=>'/uploads/'+f.filename)));
app.param('c',(q,s,n,c)=>COLS.includes(c)?n():s.status(404).end());
app.post('/api/a/:c',(q,s)=>{const o={...q.body,id:Date.now().toString(36)};db[q.params.c].push(o);save();s.json(o)});
app.put('/api/a/:c/:id',(q,s)=>{const a=db[q.params.c],i=a.findIndex(x=>x.id==q.params.id),o={...q.body,id:q.params.id};
  i<0?a.push(o):a[i]=o;save();s.json(o)});
app.delete('/api/a/:c/:id',(q,s)=>{db[q.params.c]=db[q.params.c].filter(x=>x.id!=q.params.id);save();s.json({ok:1})});
app.listen(PORT,()=>console.log('Сайт: http://localhost:'+PORT+'  Админка: http://localhost:'+PORT+ADMIN));
